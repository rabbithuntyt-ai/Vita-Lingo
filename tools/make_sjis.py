#!/usr/bin/env python3
"""Builds src/psp2-lingo-sjis.c: Shift-JIS (CP932) double-byte codes to
Unicode, for games that keep their text in Shift-JIS (common on CD consoles).
Uses Python's own codec, so no outside data.

Usage: make_sjis.py src/psp2-lingo-sjis.c
"""
import sys

LEADS = list(range(0x81, 0xA0)) + list(range(0xE0, 0xF0))


def main(out_path):
    vals = []
    for lead in LEADS:
        for trail in range(0x40, 0xFD):
            cp = 0
            if trail != 0x7F:
                try:
                    s = bytes([lead, trail]).decode("cp932")
                    if len(s) == 1:
                        cp = ord(s)
                except UnicodeDecodeError:
                    pass
            vals.append(cp if cp < 0x10000 else 0)
    with open(out_path, "w") as f:
        f.write("/* Generated by tools/make_sjis.py from Python's cp932 codec. Do not edit. */\n")
        f.write('#include "psp2-lingo-reader.h"\n\n')
        f.write("/* index: (lead row) * 189 + (trail - 0x40); lead rows are 0x81..0x9F then 0xE0..0xEF */\n")
        f.write("const uint16_t LINGO_SJIS[%d] = {\n" % len(vals))
        for i in range(0, len(vals), 16):
            f.write("\t" + ",".join("0x%04X" % v for v in vals[i:i + 16]) + ",\n")
        f.write("};\n")


if __name__ == "__main__":
    main(sys.argv[1])
