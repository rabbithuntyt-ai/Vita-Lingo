#!/usr/bin/env python3
"""Generates src/psp2-kaku-lessons.c from data/kaku/units.json and classes.json.

These are Kaku's own grammar notes, drills and catch-up classes. For the
public build the textbook's chapter titles, vocabulary lists and cast are
left out: units are titled by topic and the people in example sentences
are renamed here."""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data", "kaku")
OUT = os.path.join(ROOT, "src", "psp2-kaku-lessons.c")

REPLACE = [
    ("「げんき」という きょうかしょです。", "「ことば」という ゲームです。"),
    ("It is a textbook called Genki.", "It is a game called Kotoba."),
    ("Your exam likes this one.", "It is a favourite trick question."),
    (" — your exam asks this one.", "."),
    ("It appears constantly on exam papers.", "You will see it in instructions everywhere."),
    ("やましたせんせい", "もりせんせい"), ("Yamashita", "Mori"),
    ("たけし", "はると"), ("Takeshi", "Haruto"),
    ("メアリー", "アミ"), ("Mary", "Ami"),
    ("ジョン", "ノア"), ("John", "Noah"),
    ("ロバート", "リオ"), ("Robert", "Rio"),
]


def clean(s):
    for a, b in REPLACE:
        s = s.replace(a, b)
    return s


def c(s):
    s = clean(s or "")
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def main():
    units = json.load(open(os.path.join(DATA, "units.json"), encoding="utf-8"))
    classes = json.load(open(os.path.join(DATA, "classes.json"), encoding="utf-8"))
    out = ["/* Generated by tools/make_lessons.py from Kaku's lessons. Do not edit. */",
           '#include "psp2-kaku-lessons.h"', ""]

    for ui, u in enumerate(units):
        notes = u.get("grammar", [])
        for ni, n in enumerate(notes):
            ex = n.get("e", [])
            out.append(f"static const char* const U{ui}N{ni}EX[] = {{ " +
                       ", ".join(f"{c(a)}, {c(b)}" for a, b in ex) + (" " if ex else "NULL ") + "};")
        out.append(f"static const struct KakuNote U{ui}N[] = {{")
        for ni, n in enumerate(notes):
            out.append(f"\t{{ {c(n['t'])}, {c(n['b'])}, U{ui}N{ni}EX, {len(n.get('e', []))} }},")
        out.append("};" if notes else "\t{ 0 }\n};")
        drills = u.get("drills", [])
        out.append(f"static const struct KakuDrill U{ui}D[] = {{")
        for d in drills:
            w = d.get("w", [])[:3]
            wr = ", ".join(c(x[0]) for x in w) + ", NULL" * (3 - len(w))
            ww = ", ".join(c(x[1]) for x in w) + ", NULL" * (3 - len(w))
            out.append(f"\t{{ {c(d['q'])}, {c(d.get('ctx', ''))}, {c(d['a'])}, {{ {wr.lstrip(', ')} }}, {{ {ww.lstrip(', ')} }}, {len(w)}, {c(d.get('why', ''))} }},")
        out.append("};" if drills else "\t{ 0 }\n};")
    out.append(f"const struct KakuUnit KAKU_UNITS[{len(units)}] = {{")
    for ui, u in enumerate(units):
        topic = u["topic"]
        out.append(f"\t{{ {c(topic)}, {c(u.get('kanji', ''))}, U{ui}N, {len(u.get('grammar', []))}, U{ui}D, {len(u.get('drills', []))} }},")
    out.append("};")
    out.append(f"const int KAKU_UNIT_COUNT = {len(units)};")
    out.append("")

    for ci, k in enumerate(classes):
        body = k.get("body", [])
        out.append(f"static const char* const C{ci}B[] = {{ " + ", ".join(c(b) for b in body) + " };")
        sh = k.get("shape", [])
        out.append(f"static const char* const C{ci}S[] = {{ " + (", ".join(f"{c(a)}, {c(b)}" for a, b in sh) or "NULL") + " };")
        ex = k.get("ex", [])
        out.append(f"static const char* const C{ci}E[] = {{ " + (", ".join(", ".join(c(x) for x in (e + ['', '', ''])[:3]) for e in ex) or "NULL") + " };")
        sl = k.get("slips", [])
        out.append(f"static const char* const C{ci}L[] = {{ " + (", ".join(", ".join(c(x) for x in (e + ['', '', ''])[:3]) for e in sl) or "NULL") + " };")
        ch = k.get("check", [])
        out.append(f"static const struct KakuCheck C{ci}K[] = {{")
        for q in ch:
            o = (q["o"] + ["", "", "", ""])[:4]
            out.append(f"\t{{ {c(q['q'])}, {{ {', '.join(c(x) for x in o)} }}, {min(len(q['o']), 4)}, {q['a']}, {c(q.get('why', ''))} }},")
        out.append("};" if ch else "\t{ 0 }\n};")
    out.append(f"const struct KakuClass KAKU_CLASSES[{len(classes)}] = {{")
    for ci, k in enumerate(classes):
        out.append(f"\t{{ {c(k['t'])}, {c(k.get('idea', ''))}, C{ci}B, {len(k.get('body', []))}, C{ci}S, {len(k.get('shape', []))}, "
                   f"C{ci}E, {len(k.get('ex', []))}, C{ci}L, {len(k.get('slips', []))}, C{ci}K, {len(k.get('check', []))} }},")
    out.append("};")
    out.append(f"const int KAKU_CLASS_COUNT = {len(classes)};")
    text = "\n".join(out) + "\n"
    for a, _ in REPLACE:
        if a in text and a not in ("Yamashita",):
            raise SystemExit(f"replacement left behind: {a}")
    open(OUT, "w", encoding="utf-8").write(text)
    print(f"{len(units)} units, {sum(len(u.get('drills', [])) for u in units)} drills, "
          f"{sum(len(u.get('grammar', [])) for u in units)} notes, {len(classes)} classes -> {OUT}")


if __name__ == "__main__":
    main()
