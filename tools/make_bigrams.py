#!/usr/bin/env python3
"""Builds src/psp2-lingo-bigram.c: how often one kana follows another in
Japanese. Lingo uses it to recognise a game's text in memory before it knows
the game's character encoding (real text scores high, other data does not).

The "text" is common JMdict words (CC BY-SA 4.0, EDRDG) strung together with
particles, the conjugated forms of common verbs and adjectives, and the
conversational lines of Kaku's lessons, which together come close enough to
game dialogue for this purpose.

Usage: make_bigrams.py jamdict.db data/kaku src/psp2-lingo-bigram.c
"""
import math
import random
import sqlite3
import sys

FIRST, LAST = 0x3041, 0x3093  # ぁ .. ん
N = LAST - FIRST + 2  # + ー
JOINS = ["は", "が", "を", "に", "の", "で", "と", "も", "へ", "から", "まで", "よ", "ね", "か",
         "です", "ます", "した", "して", "ない", "だ", "った", "って", "たい", "ました"]


def idx(ch):
    o = ord(ch)
    if 0x30A1 <= o <= 0x30F3:
        o -= 0x60
    if ch == "ー":
        return N - 1
    if FIRST <= o <= LAST:
        return o - FIRST
    return -1


ROWS = {"う": "わいうえお", "く": "かきくけこ", "ぐ": "がぎぐげご", "す": "さしすせそ", "つ": "たちつてと",
        "ぬ": "なにぬねの", "ぶ": "ばびぶべぼ", "む": "まみむめも", "る": "らりるれろ"}
TE = {"う": "って", "つ": "って", "る": "って", "く": "いて", "ぐ": "いで", "す": "して", "ぬ": "んで", "ぶ": "んで", "む": "んで"}


def conjugate(reading, pos):
    out = []
    if pos.startswith("Ichidan verb"):
        st = reading[:-1]
        out += [st + e for e in ("ます", "ました", "ません", "ない", "なかった", "て", "た", "よう", "られる", "たい", "ている")]
    elif pos.startswith("Godan verb") and reading[-1] in ROWS:
        st, end = reading[:-1], reading[-1]
        row = ROWS[end]
        te = TE[end]
        if reading == "いく":
            te = "って"
        out += [st + row[1] + e for e in ("ます", "ました", "ません", "たい")]
        out += [st + row[0] + e for e in ("ない", "なかった", "れる")]
        out += [st + te, st + te[:-1] + ("だ" if te.endswith("で") else "た"), st + row[4] + "う", st + row[3] + "ば"]
    elif pos.startswith("adjective (keiyoushi)") and reading.endswith("い"):
        st = reading[:-1]
        out += [st + e for e in ("く", "かった", "くない", "くて", "ければ")]
    return out


def main(db_path, kaku_dir, out_path):
    import json, os, re
    db = sqlite3.connect(db_path)
    common = set()
    for (kid,) in db.execute("SELECT kid FROM KNP WHERE text IN ('ichi1','news1','spec1','spec2','gai1')"):
        common.add(kid)
    kana_by_seq = {}
    words = []
    for kid, idseq, t in db.execute("SELECT ID, idseq, text FROM Kana"):
        if kid in common:
            words.append(t)
            kana_by_seq.setdefault(idseq, t)
    forms = []
    for idseq, text in db.execute("SELECT s.idseq, p.text FROM pos p JOIN Sense s ON s.ID = p.sid"):
        r = kana_by_seq.get(idseq)
        if r:
            forms += conjugate(r, text)
    lessons = ""
    for name in ("units.json", "classes.json"):
        with open(os.path.join(kaku_dir, name), encoding="utf-8") as f:
            lessons += f.read()
    lines = re.findall(r"[ぁ-んァ-ヶー]{2,}", lessons)
    rnd = random.Random(1)
    counts = [[1.0] * N for _ in range(N)]  # add-one smoothing

    def feed(text, weight):
        prev = -1
        for ch in text:
            i = idx(ch)
            if i >= 0 and prev >= 0:
                counts[prev][i] += weight
            prev = i

    for _ in range(2):
        rnd.shuffle(words)
        feed("".join(w + rnd.choice(JOINS) for w in words), 1)
    for _ in range(3):
        rnd.shuffle(forms)
        feed("".join(f + " " + rnd.choice(JOINS) for f in forms), 1)
    for w in lines:
        feed(w, 40)
    rows = []
    for a in range(N):
        tot = sum(counts[a])
        # log2(P(b|a) * N): above zero when b follows a more often than chance
        rows.append([max(-127, min(127, round(8 * math.log2(c / tot * N)))) for c in counts[a]])
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("/* Generated by tools/make_bigrams.py from JMdict (CC BY-SA 4.0, EDRDG). Do not edit. */\n")
        f.write('#include "psp2-lingo-reader.h"\n\n')
        f.write("/* [a][b]: 8 * log2(P(b follows a) / chance), kana ぁ..ん then ー */\n")
        f.write("const int8_t LINGO_BIGRAM[LINGO_BIGRAM_N][LINGO_BIGRAM_N] = {\n")
        for r in rows:
            f.write("\t{" + ",".join(str(v) for v in r) + "},\n")
        f.write("};\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], sys.argv[3])
