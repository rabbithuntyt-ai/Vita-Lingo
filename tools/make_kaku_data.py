#!/usr/bin/env python3
"""Generates src/psp2-kaku-data.c from Kaku's reference data in data/kaku.

Stroke paths are KanjiVG (Ulrich Apel, CC BY-SA 3.0); kanji meanings and
readings are KANJIDIC (EDRDG, CC BY-SA 4.0). Each stroke is flattened here
into a polyline so the Vita does no SVG parsing at runtime.
"""
import json
import math
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data", "kaku")
OUT = os.path.join(ROOT, "src", "psp2-kaku-data.c")


def parse_path(d):
    tk = re.findall(r"[MmCcSsLlHhVvZz]|[+-]?(?:\d+\.\d*|\.\d+|\d+)(?:[eE][+-]?\d+)?", d)
    i = 0
    cmd = ""
    x = y = sx = sy = 0.0
    c2 = None
    segs = []

    def n():
        nonlocal i
        v = float(tk[i])
        i += 1
        return v

    def cub(x1, y1, x2, y2, x3, y3):
        nonlocal x, y, c2
        segs.append((x, y, x1, y1, x2, y2, x3, y3))
        c2 = (x2, y2)
        x, y = x3, y3

    def line(x3, y3):
        nonlocal x, y, c2
        segs.append((x, y, x, y, x3, y3, x3, y3))
        c2 = None
        x, y = x3, y3

    while i < len(tk):
        if re.match(r"[A-Za-z]", tk[i]):
            cmd = tk[i]
            i += 1
        if cmd == "M":
            x, y = n(), n(); sx, sy = x, y; c2 = None; cmd = "L"
        elif cmd == "m":
            x += n(); y += n(); sx, sy = x, y; c2 = None; cmd = "l"
        elif cmd == "C":
            cub(n(), n(), n(), n(), n(), n())
        elif cmd == "c":
            a, b = x, y
            cub(a + n(), b + n(), a + n(), b + n(), a + n(), b + n())
        elif cmd == "S":
            x1, y1 = (2 * x - c2[0], 2 * y - c2[1]) if c2 else (x, y)
            cub(x1, y1, n(), n(), n(), n())
        elif cmd == "s":
            a, b = x, y
            x1, y1 = (2 * x - c2[0], 2 * y - c2[1]) if c2 else (x, y)
            cub(x1, y1, a + n(), b + n(), a + n(), b + n())
        elif cmd == "L":
            line(n(), n())
        elif cmd == "l":
            a, b = x, y
            line(a + n(), b + n())
        elif cmd == "H":
            line(n(), y)
        elif cmd == "h":
            line(x + n(), y)
        elif cmd == "V":
            line(x, n())
        elif cmd == "v":
            line(x, y + n())
        elif cmd in "Zz":
            line(sx, sy)
        else:
            i += 1
    return segs


def flatten(segs, steps=16):
    out = []
    for k, (x0, y0, x1, y1, x2, y2, x3, y3) in enumerate(segs):
        for j in range(0 if k == 0 else 1, steps + 1):
            t = j / steps
            u = 1 - t
            a, b, c, e = u * u * u, 3 * u * u * t, 3 * u * t * t, t * t * t
            out.append((a * x0 + b * x1 + c * x2 + e * x3, a * y0 + b * y1 + c * y2 + e * y3))
    dd = []
    for p in out:
        if not dd or math.dist(dd[-1], p) > 0.01:
            dd.append(p)
    return dd


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    kvg = json.load(open(os.path.join(DATA, "kvg.json"), encoding="utf-8"))
    kanji = json.load(open(os.path.join(DATA, "kanji.json"), encoding="utf-8"))
    romaji = json.load(open(os.path.join(DATA, "romaji.json"), encoding="utf-8"))
    look = json.load(open(os.path.join(DATA, "lookalike.json"), encoding="utf-8"))

    points = []      # flat float pairs
    strokes = []     # (first point, count)
    lines = ["/* Generated by tools/make_kaku_data.py. Do not edit. */",
             "/* Stroke data: KanjiVG, (C) 2009-2011 Ulrich Apel, CC BY-SA 3.0, https://kanjivg.tagaini.net */",
             "/* Kanji meanings and readings: KANJIDIC, EDRDG, CC BY-SA 4.0 */",
             '#include "psp2-kaku.h"', ""]

    def add_strokes(paths):
        first = len(strokes)
        for d in paths:
            pts = flatten(parse_path(d))
            strokes.append((len(points), len(pts)))
            points.extend(pts)
        return first, len(paths)

    kana_rows = []
    for ch, info in kvg.items():
        first, n = add_strokes(info["s"])
        nums = info.get("n", [])
        kana_rows.append((ch, romaji.get(ch, ""), look.get(ch, ""), first, n))

    kanji_rows = []
    group_of = {}
    for gi, (name, chars) in enumerate(kanji["groups"]):
        for c in chars:
            group_of[c] = gi
    for ch, info in kanji["k"].items():
        first, n = add_strokes(info["s"])
        on = "、".join(info.get("on", []))
        kun = "、".join(info.get("kun", [])).replace(".", "")
        kanji_rows.append((ch, info.get("m", ""), on, kun, group_of.get(ch, 0), first, n))

    lines.append(f"const float KAKU_POINTS[{len(points) * 2}] = {{")
    row = []
    for x, y in points:
        row.append(f"{x:.2f}f,{y:.2f}f")
        if len(row) == 8:
            lines.append("\t" + ",".join(row) + ",")
            row = []
    if row:
        lines.append("\t" + ",".join(row) + ",")
    lines.append("};")
    lines.append(f"const struct KakuStroke KAKU_STROKES[{len(strokes)}] = {{")
    for first, cnt in strokes:
        lines.append(f"\t{{ {first}, {cnt} }},")
    lines.append("};")
    lines.append(f"const struct KakuKana KAKU_KANA[{len(kana_rows)}] = {{")
    for ch, ro, lk, first, n in kana_rows:
        lines.append(f"\t{{ {cstr(ch)}, {cstr(ro)}, {cstr(lk)}, {first}, {n} }},")
    lines.append("};")
    lines.append(f"const int KAKU_KANA_COUNT = {len(kana_rows)};")
    lines.append(f"const struct KakuKanji KAKU_KANJI[{len(kanji_rows)}] = {{")
    for ch, m, on, kun, g, first, n in kanji_rows:
        lines.append(f"\t{{ {cstr(ch)}, {cstr(m)}, {cstr(on)}, {cstr(kun)}, {g}, {first}, {n} }},")
    lines.append("};")
    lines.append(f"const int KAKU_KANJI_COUNT = {len(kanji_rows)};")
    lines.append(f"const char* const KAKU_GROUPS[{len(kanji['groups'])}] = {{")
    for name, _ in kanji["groups"]:
        lines.append(f"\t{cstr(name)},")
    lines.append("};")
    lines.append(f"const int KAKU_GROUP_COUNT = {len(kanji['groups'])};")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{len(kana_rows)} kana, {len(kanji_rows)} kanji, {len(strokes)} strokes, {len(points)} points -> {OUT}")


if __name__ == "__main__":
    main()
